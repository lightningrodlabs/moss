// Pure helpers for scripts/update-asr-catalog.mjs: the list of whisper
// models Moss offers, how to find each one's checksum on HuggingFace, and
// how to render the generated data module the main process compiles in.
//
// To add or drop a model, edit ASR_CATALOG_MODELS and run
// `yarn update:asr-catalog`.

/**
 * @typedef {'fast' | 'ok' | 'slow'} LatencyTier
 * @typedef {{ id: string, latencyTier: LatencyTier }} CatalogModel
 * @typedef {{ id: string, latencyTier: LatencyTier, sha256: string, sizeBytes: number }} CatalogRow
 */

/**
 * The models Moss can download, in the order the settings pane lists
 * them. The tier is a rough CPU latency class for the size; tools use it
 * to decide whether live captions are worth offering.
 * @type {readonly CatalogModel[]}
 */
export const ASR_CATALOG_MODELS = Object.freeze([
  { id: 'tiny', latencyTier: 'fast' },
  { id: 'tiny.en', latencyTier: 'fast' },
  { id: 'base', latencyTier: 'ok' },
  { id: 'base.en', latencyTier: 'ok' },
  { id: 'small', latencyTier: 'ok' },
  { id: 'small.en', latencyTier: 'ok' },
  { id: 'medium', latencyTier: 'slow' },
  { id: 'medium.en', latencyTier: 'slow' },
  { id: 'large-v3-turbo', latencyTier: 'slow' },
  { id: 'large-v3', latencyTier: 'slow' },
]);

const HF_RAW_BASE = 'https://huggingface.co/ggerganov/whisper.cpp/raw/main/';

/**
 * The `raw/` path returns the git-lfs pointer (a few lines of text with
 * the checksum and size) instead of redirecting to the multi-gigabyte
 * binary that `resolve/` serves.
 * @param {string} id
 */
export function pointerUrl(id) {
  return `${HF_RAW_BASE}ggml-${id}.bin`;
}

/**
 * @param {string} text
 * @returns {{ sha256: string, sizeBytes: number }}
 */
export function parseLfsPointer(text) {
  const oid = /^oid sha256:([0-9a-f]{64})$/m.exec(text);
  const size = /^size (\d+)$/m.exec(text);
  if (!oid || !size) {
    throw new Error(`not an LFS pointer: ${text.slice(0, 80).replace(/\n/g, ' ')}`);
  }
  return { sha256: oid[1], sizeBytes: Number(size[1]) };
}

/**
 * Render the TypeScript module that modelCatalog.ts imports. Output is a
 * pure function of the rows so `--check` can compare it to the committed
 * file byte for byte.
 * @param {readonly CatalogRow[]} rows
 */
export function renderCatalogData(rows) {
  const lines = [
    '// Generated by scripts/update-asr-catalog.mjs from the HuggingFace LFS',
    '// pointers of ggerganov/whisper.cpp. Do not edit by hand: change',
    '// ASR_CATALOG_MODELS in scripts/asr-catalog-lib.mjs and run',
    '// `yarn update:asr-catalog`.',
    '',
    "import type { AsrLatencyTier } from '@theweave/moss-types';",
    '',
    'export interface AsrModelCatalogRow {',
    '  id: string;',
    '  latencyTier: AsrLatencyTier;',
    '  sha256: string;',
    '  sizeBytes: number;',
    '}',
    '',
    'export const ASR_MODEL_CATALOG_DATA: readonly AsrModelCatalogRow[] = Object.freeze([',
  ];
  for (const r of rows) {
    lines.push('  {');
    lines.push(`    id: '${r.id}',`);
    lines.push(`    latencyTier: '${r.latencyTier}',`);
    lines.push(`    sha256: '${r.sha256}',`);
    lines.push(`    sizeBytes: ${groupDigits(r.sizeBytes)},`);
    lines.push('  },');
  }
  lines.push(']);');
  return lines.join('\n') + '\n';
}

/** 3095033483 → 3_095_033_483, matching the repo's numeric literal style. */
function groupDigits(n) {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, '_');
}
