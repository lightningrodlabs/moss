/**
 * The two halves of a peer's name: a describing word and a thing, so a name
 * reads as a name — "Drifting Lantern" rather than a pair of unrelated words.
 *
 * Both lists are hand-picked rather than filtered from a general word list.
 * Filtering was tried against a curated public list and kept leaking animals,
 * people, body parts, countries and surnames, and no amount of exclusion proves
 * a list safe. These hold only things: no animals, no people or roles, no body
 * parts, no colours, no nationalities or religions, nothing about health,
 * appearance or violence — because a name is shown to strangers in a room and
 * the pairing is never reviewed by anyone before they see it.
 *
 * 256 of each is 65,536 names. That is small enough to read end to end, which
 * is the only check that catches a bad pairing, and the size is not what keeps
 * the exchange safe: a name held by two people at once is shown as ambiguous
 * and refused. Each list is a power of two so a name takes a whole number of
 * bits from the digest.
 *
 * Order is significant: it is what makes a name reproducible from a key, so
 * both machines must hold the same list in the same order.
 */

